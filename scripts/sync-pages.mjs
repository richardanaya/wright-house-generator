import { cp, mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dist = join(root, 'dist');
const builtHtmlPath = join(dist, 'index.dev.html');
const appDir = join(root, 'app');

if (!existsSync(builtHtmlPath)) {
  const listing = existsSync(dist) ? (await readdir(dist)).join(', ') : '(missing)';
  throw new Error(`Expected ${builtHtmlPath} after vite build. dist contains: ${listing}`);
}

const built = await readFile(builtHtmlPath, 'utf8');
if (!built.includes('./assets/')) {
  throw new Error("Built HTML has no ./assets/ URLs. Vite base must be './' for the Pages bundle.");
}
if (built.includes('/src/main.ts')) {
  throw new Error('Built HTML still references /src/main.ts.');
}

await writeFile(join(dist, 'index.html'), built);

const pagesHtml = built.replaceAll('./assets/', './app/assets/');
if (pagesHtml.includes('/src/main.ts') || pagesHtml.includes('./assets/')) {
  throw new Error('Pages index.html still points at source or dist-relative assets.');
}
if (!pagesHtml.includes('./app/assets/')) {
  throw new Error('Pages index.html is missing ./app/assets/ references.');
}

const refs = [...pagesHtml.matchAll(/(?:src|href)="(\.\/app\/assets\/[^"]+)"/g)].map((match) => match[1]);
if (refs.length === 0) {
  throw new Error('Pages index.html has no asset references.');
}

await rm(appDir, { recursive: true, force: true });
await mkdir(join(appDir, 'assets'), { recursive: true });
await cp(join(dist, 'assets'), join(appDir, 'assets'), { recursive: true });

for (const ref of refs) {
  const file = join(root, ref.slice(2));
  if (!existsSync(file)) throw new Error(`Pages HTML references missing file ${ref}`);
}

const banner =
  '<!-- Generated by `npm run build` from index.dev.html. Commit this file with app/. -->\n';
await writeFile(join(root, 'index.html'), pagesHtml.replace('<!doctype html>\n', `<!doctype html>\n${banner}`));
